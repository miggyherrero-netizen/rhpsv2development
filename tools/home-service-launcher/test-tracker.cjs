"use strict";
const assert = require("node:assert/strict");
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || "playwright");
const KEY = "herrero-ai-work-v1";
const BASE = "http://127.0.0.1:4310/";

(async () => {
  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ acceptDownloads: true });
  const page = await context.newPage();
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  const count = async (n) => assert.equal(await page.locator(".work-card").count(), n);
  const field = (name) => page.locator(`#trackerForm [name="${name}"]`);
  try {
    await page.goto(BASE);
    await page.waitForSelector(".work-card");
    await count(5);
    const original = await page.evaluate((key) => localStorage.getItem(key), KEY);
    assert.equal(JSON.parse(original).records.filter((r) => r.review).length, 5);
    await page.getByRole("button", { name: "Edit / rate", exact: true }).first().click();
    await field("ownerRating").selectOption("4");
    await field("ownerNotes").fill('Owner note <img src=x onerror="alert(1)">');
    await page.getByRole("button", { name: "Save work", exact: true }).click();
    await page.reload();
    await page.waitForSelector(".work-card");
    assert.ok((await page.locator(".work-card").first().innerText()).includes("Your rating: 4 / 5"));
    assert.equal(await page.locator(".work-note img").count(), 0);
    const edited = JSON.parse(await page.evaluate((key) => localStorage.getItem(key), KEY));
    assert.deepEqual(edited.records[0].review, JSON.parse(original).records[0].review);
    await page.getByRole("button", { name: "Add work", exact: true }).click();
    await field("agent").fill("Test agent");
    await field("title").fill("Tracker persistence test");
    await field("url").fill("javascript:alert(1)");
    await page.getByRole("button", { name: "Save work", exact: true }).click();
    await count(5);
    assert.match(await page.locator("#trackerMessage").innerText(), /HTTPS/);
    await field("url").fill("https://github.com/miggyherrero-netizen/rhpsv2development/pull/37");
    await page.getByRole("button", { name: "Save work", exact: true }).click();
    await count(6);
    await page.locator("#trackerSearch").fill("persistence test");
    await count(1);
    await page.locator("#trackerFilter").selectOption("Merged");
    await count(0);
    await page.locator("#trackerSearch").fill("");
    await count(5);
    await page.locator("#trackerFilter").selectOption("");
    const downloadPromise = page.waitForEvent("download");
    await page.getByRole("button", { name: "Export backup", exact: true }).click();
    const download = await downloadPromise;
    const stream = await download.createReadStream();
    const chunks = []; for await (const chunk of stream) chunks.push(chunk);
    const exported = JSON.parse(Buffer.concat(chunks).toString());
    assert.equal(exported.records.length, 6);
    const upload = async (data) => page.locator("#trackerImportFile").setInputFiles({ name: "backup.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(data)) });
    await upload({ version: 1, records: [{ ...exported.records[0], url: "javascript:alert(1)" }] });
    await page.waitForFunction(() => document.querySelector("#trackerMessage").textContent.includes("Import stopped"));
    await count(6);
    await upload({ version: 1, records: [{ ...exported.records[0], ownerRating: 9 }] });
    await page.waitForFunction(() => document.querySelector("#trackerMessage").textContent.includes("Ratings must"));
    await count(6);
    page.once("dialog", (dialog) => dialog.accept());
    await upload(JSON.parse(original));
    await page.waitForFunction(() => document.querySelectorAll(".work-card").length === 5);
    await page.reload(); await page.waitForSelector(".work-card"); await count(5);
    const other = await context.newPage(); await other.goto(BASE); await other.waitForSelector(".work-card");
    await other.evaluate((key) => { const data = JSON.parse(localStorage.getItem(key)); data.records[0].ownerNotes = "Other tab"; localStorage.setItem(key, JSON.stringify(data)); }, KEY);
    await page.getByRole("button", { name: "Edit / rate", exact: true }).first().click();
    await field("ownerNotes").fill("Stale write");
    await page.getByRole("button", { name: "Save work", exact: true }).click();
    assert.match(await page.locator("#trackerMessage").innerText(), /Another tab changed/);
    await page.reload(); await page.waitForSelector(".work-card");
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.locator(".work-card summary").first().click();
    assert.equal(await page.locator(".work-card details").first().getAttribute("open"), "");
    if (process.env.TRACKER_SCREENSHOT) await page.screenshot({ path: process.env.TRACKER_SCREENSHOT, fullPage: true });
    await page.getByRole("button", { name: "Edit / rate", exact: true }).first().click();
    await field("ownerNotes").fill("Quota test");
    await page.evaluate(() => { Storage.prototype.setItem = () => { throw new DOMException("Quota exceeded", "QuotaExceededError"); }; });
    await page.getByRole("button", { name: "Save work", exact: true }).click();
    assert.match(await page.locator("#trackerMessage").innerText(), /Could not save/);
    assert.equal((await page.evaluate((key) => JSON.parse(localStorage.getItem(key)), KEY)).records[0].ownerNotes, "Other tab");
    await page.reload(); await page.waitForSelector(".work-card");
    page.once("dialog", (dialog) => dialog.accept());
    await page.getByRole("button", { name: "Remove entry", exact: true }).first().click();
    await count(4);
    await page.evaluate((key) => localStorage.setItem(key, "{corrupt-json"), KEY);
    await page.reload();
    await page.waitForFunction(() => document.querySelector("#trackerMessage").textContent.includes("could not be loaded"));
    assert.equal(await page.evaluate((key) => localStorage.getItem(key), KEY), "{corrupt-json");
    assert.deepEqual(errors, []);
    console.log("PASS: 5 seeds, rating + notes persistence, review preservation, escaped notes, unsafe URL rejection, add, search, status filter, export, invalid import preservation, restore, multi-tab conflict, mobile overflow, details, quota failure, remove, corrupt-storage preservation; no page errors.");
  } finally { await context.close(); await browser.close(); }
})().catch((error) => { console.error(error); process.exitCode = 1; });
